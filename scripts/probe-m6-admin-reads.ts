import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {eq} from 'drizzle-orm';
import {drizzle} from 'drizzle-orm/node-postgres';
import {migrate} from 'drizzle-orm/node-postgres/migrator';
import {Client} from 'pg';

import {getServerEnv} from '../src/config/env.ts';
import {createDatabase} from '../src/db/client.ts';
import {DomainError} from '../src/db/contracts.ts';
import {authUser, authSession} from '../src/db/schema/auth.ts';
import {operatorRoles} from '../src/db/schema/operator.ts';
import {userAccessControls} from '../src/db/schema/access.ts';
import {affiliateReviewRecords, affiliateCorrectionCases, affiliateSettings} from '../src/db/schema/affiliate.ts';
import {billingAccounts, billingCustomerHistory} from '../src/db/schema/billing.ts';
import {operatorTenantAccess} from '../src/db/schema/operations.ts';
import {creditAccounts} from '../src/db/schema/workspace.ts';
import {createTeamWorkspace} from '../src/modules/workspaces/commands.ts';
import {recordTrustedSecondFactor} from '../src/modules/operations/authorize.ts';
import {listAdminUsers, listAdminWorkspaces, listAdminBilling, listAdminGenerations, listAdminAudit, readAdminMe, readAdminWorkspace} from '../src/modules/operations/queries.ts';
import {listAffiliateReviews, listAffiliateHolds, readAffiliateAdminStatus} from '../src/modules/affiliates/queries.ts';
import {recordOperatorAudit} from '../src/modules/operations/audit.ts';
import {reconcilePayment} from '../src/modules/billing/reconcile-payment.ts';
import {createGenerationTask} from '../src/modules/generation/create.ts';
import {createServerQuote, DEFAULT_MODEL_ID} from '../src/config/models.ts';

const configured = new URL(getServerEnv().databaseUrl);
assert(['localhost', '127.0.0.1', '[::1]'].includes(configured.hostname));
const databaseName = `m6_reads_${randomUUID().replaceAll('-', '')}`;
const admin = new Client({connectionString: configured.toString()});
const local = new URL(configured); local.pathname = '/'+databaseName;
const code = (expected: string) => (error: unknown) => error instanceof DomainError && error.code === expected;
await admin.connect();
await admin.query(`create database "${databaseName}"`);
const database = createDatabase({connectionString: local.toString()});
try {
  const migration = new Client({connectionString: local.toString()}); await migration.connect();
  try { await migrate(drizzle(migration), {migrationsFolder: 'src/db/migrations'}); } finally { await migration.end(); }
  const db = database.db;
  const now = new Date();
  await db.insert(authUser).values(['operator', 'support', 'owner', 'disabled', 'auth-disabled'].map(id => ({id, name: id, email: `${id}@example.test`, emailVerified: true, twoFactorEnabled: true, disabledAt:id==='auth-disabled'?now:null, createdAt: now, updatedAt: now})));
  await db.insert(authSession).values(['operator', 'support', 'owner'].map(id => ({id: `${id}-session`, userId: id, token: `${id}-token`, expiresAt: new Date(now.getTime()+3600000), createdAt: now, updatedAt: now})));
  await db.insert(operatorRoles).values([{userId:'operator',role:'operator',grantedAt:now,updatedAt:now},{userId:'support',role:'support',grantedAt:now,updatedAt:now}]);
  const operator={userId:'operator',sessionId:'operator-session'};
  const support={userId:'support',sessionId:'support-session'};
  const owner={userId:'owner',sessionId:'owner-session'};
  await recordTrustedSecondFactor(db,operator,now); await recordTrustedSecondFactor(db,support,now);
  await db.insert(userAccessControls).values({userId:'disabled',status:'disabled',reason:'Local read probe',disabledAt:now,createdAt:now,updatedAt:now,version:1});
  const first=(await createTeamWorkspace(db,owner,'Alpha read probe')).workspaceId;
  const second=(await createTeamWorkspace(db,owner,'Beta read probe')).workspaceId;
  await db.insert(creditAccounts).values({workspaceId:first,version:0n,createdAt:now,updatedAt:now}).onConflictDoNothing();
  assert.equal((await readAdminMe(db,support)).role,'support');
  for(const call of [listAdminUsers,listAdminWorkspaces,listAdminBilling,listAdminGenerations,listAdminAudit,listAffiliateReviews,listAffiliateHolds]) await assert.rejects(()=>call(db,owner),code('FORBIDDEN'));
  assert.equal((await listAdminUsers(db,support,{status:'active'})).items.length,3,'Missing access rows represent active users in the filter too.');
  assert.deepEqual(new Set((await listAdminUsers(db,support,{status:'disabled'})).items.map(row=>row.id)),new Set(['disabled','auth-disabled']));
  const users=await listAdminUsers(db,support,{page:1,pageSize:2,sort:'email',direction:'asc'});
  assert.equal(users.hasMore,true); assert.equal(users.items.length,2);
  assert(users.items.every(row=>String(row.email).includes('***') && !('twoFactorEnabled' in row)));
  assert.equal((await listAdminUsers(db,support,{filter:'owner',sort:'email',direction:'desc'})).items.length,1);
  assert.equal((await listAdminUsers(db,support,{page:-1,pageSize:1000,sort:'createdAt',direction:'asc'})).pageSize,100);
  for(const input of [{filter:'x'.repeat(101)},{filter:'bad\nfilter'},{status:'unsupported'},{sort:'password'}]) await assert.rejects(()=>listAdminUsers(db,support,input),code('VALIDATION'));
  const spaces=await listAdminWorkspaces(db,support,{pageSize:1});
  assert(spaces.hasMore); assert.equal(spaces.items.length,1);
  assert.equal((await listAdminWorkspaces(db,support,{filter:'Alpha'})).items[0]?.id,first);
  await db.update(billingAccounts).set({status:'hold',holdReason:'Local read probe'}).where(eq(billingAccounts.workspaceId,second));
  assert.equal((await listAdminWorkspaces(db,support,{status:'hold'})).items[0]?.id,second);
  await assert.rejects(()=>listAdminWorkspaces(db,support,{status:'unknown'}),code('VALIDATION'));
  await assert.rejects(()=>readAdminWorkspace(db,support,first,'Support cannot open tenant details'),code('FORBIDDEN'));
  await assert.rejects(()=>readAdminWorkspace(db,operator,randomUUID(),'Missing workspace'),code('NOT_FOUND'));
  assert.equal((await readAdminWorkspace(db,operator,first,'Investigate local sample')).id,first);
  assert.equal((await db.select().from(operatorTenantAccess)).length,1);
  const customerId='fixture-read-customer';
  await db.insert(billingCustomerHistory).values({workspaceId:first,provider:'fixture',customerId,validFrom:now,changeReason:'Local read probe'});
  await reconcilePayment(db,{provider:'fixture',eventId:'read-event',eventType:'payment_intent.succeeded',workspaceId:first,customerId,paymentIntentId:'read-payment',productKey:'fixture-pack',amountMinor:'900',currency:'usd'},now);
  const billing=await listAdminBilling(db,support,{status:'paid'});
  assert.equal(billing.items.length,1); assert.equal(billing.items[0]?.paidMinor,'900');
  assert(!('catalogSnapshot' in billing.items[0]!));
  const quote=createServerQuote(DEFAULT_MODEL_ID,'1',{now});
  await createGenerationTask(db,{actor:owner,workspaceId:first,idempotencyKey:'read-generation',input:{prompt:'Local admin read probe'},quote,now});
  const generations=await listAdminGenerations(db,support,{status:'queued'});
  assert.equal(generations.items.length,1); assert(!('inputSnapshot' in generations.items[0]!));
  await db.transaction(tx=>recordOperatorAudit(tx,{actorUserId:'operator',workspaceId:first,commandName:'read.probe',commandKey:'read-audit',payload:{private:'must not appear'},now}));
  assert(!(await listAdminAudit(db,support)).items.some(row=>'payload' in row));
  for(const call of [listAdminBilling,listAdminGenerations]) await assert.rejects(()=>call(db,support,{status:'invalid'}),code('VALIDATION'));
  await db.insert(affiliateReviewRecords).values([{id:randomUUID(),workspaceId:first,paymentReference:'read-one',status:'held',reason:'history incomplete',policyVersion:1,createdAt:now,updatedAt:now},{id:randomUUID(),workspaceId:second,paymentReference:'read-two',status:'eligible',reason:'verified',policyVersion:1,refreshedAt:now,createdAt:now,updatedAt:now}]);
  await db.insert(affiliateCorrectionCases).values([{id:randomUUID(),workspaceId:first,reason:'local open',status:'open',createdAt:now},{id:randomUUID(),workspaceId:second,reason:'local resolved',status:'resolved',createdAt:now,resolvedAt:now}]);
  assert((await listAffiliateReviews(db,support,{pageSize:1})).hasMore);
  assert.equal((await listAffiliateReviews(db,support,{status:'held'})).items[0]?.refreshedAt,null);
  assert((await listAffiliateReviews(db,support,{status:'eligible'})).items[0]?.refreshedAt);
  assert((await listAffiliateHolds(db,support,{pageSize:1})).hasMore);
  assert.equal((await listAffiliateHolds(db,support,{status:'open'})).items[0]?.resolvedAt,null);
  assert((await listAffiliateHolds(db,support,{status:'resolved'})).items[0]?.resolvedAt);
  for(const call of [listAffiliateReviews,listAffiliateHolds]) for(const input of [{page:10001},{pageSize:0},{status:'invalid'}]) await assert.rejects(()=>call(db,support,input),code('VALIDATION'));
  assert.equal((await readAffiliateAdminStatus(db,support)).integrationStatus,'disabled');
  await db.update(affiliateSettings).set({enabled:'enabled',accountId:'local',programId:'local',accountCheckpointAt:now}).where(eq(affiliateSettings.id,'default'));
  const configuredStatus=await readAffiliateAdminStatus(db,support);
  assert.equal(configuredStatus.integrationStatus,'pending','Configuration without provider readback must remain pending.');
  assert.equal(configuredStatus.accountSyncStatus,'pending','Configuration cannot fabricate a successful provider sync.');
  await db.update(operatorRoles).set({revokedAt:now}).where(eq(operatorRoles.userId,'support'));
  await assert.rejects(()=>listAffiliateReviews(db,support),code('FORBIDDEN'));
  console.log(JSON.stringify({status:'PASS',groups:7,checks:['live role isolation','redacted bounded user filters','workspace filters and audited tenant access','redacted billing and generation projections','audit payload exclusion','affiliate pagination/status/version projections','disabled/unavailable provider visibility and immediate role revocation']}));
} finally {
  await database.pool.end();
  await admin.query(`drop database "${databaseName}" with (force)`);
  await admin.end();
}
