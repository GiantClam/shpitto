import {existsSync, readFileSync} from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => readFileSync(path.join(root, file), 'utf8');
const checks = [];
const requireFile = (file) => { if (!existsSync(path.join(root, file))) throw new Error(`missing ${file}`); checks.push(file); };
requireFile('Dockerfile');
requireFile('vercel.json');
requireFile('src/app/api/healthz/route.ts');
requireFile('scripts/migrate.ts');
requireFile('scripts/maintenance/backup-db.mjs');
requireFile('scripts/maintenance/restore-db.mjs');
requireFile('scripts/maintenance/verify-backup.mjs');
requireFile('content/docs/v1/template/deploy-managed.mdx');
requireFile('content/docs/v1/template/deploy-docker.mdx');
requireFile('content/docs/v1/template/deployment-checklist.mdx');
requireFile('content/docs/v1/template/upgrade-recovery.mdx');
const docker = read('Dockerfile');
const next = read('next.config.ts');
for (const marker of ['pnpm install --frozen-lockfile', 'pnpm build', 'build-only-dummy-secret-never-used-at-runtime', 'server.js', '/api/healthz', 'COPY --from=build /app/public ./public', 'COPY --from=build /app/content/docs ./content/docs']) if (!docker.includes(marker)) throw new Error(`Dockerfile is missing ${marker}`);
if (!next.includes("output: 'standalone'")) throw new Error('Next configuration must produce a standalone runtime.');
const env = read('src/config/env.ts');
for (const marker of ["nodeEnv === 'production'", 'GENERATION_DRIVER', 'STORAGE_DRIVER', 'MAIL_DRIVER']) if (!env.includes(marker)) throw new Error(`production guard is missing ${marker}`);
const migration = read('scripts/migrate.ts');
for (const marker of ['pg_advisory_lock', 'migrationsFolder', 'pg_advisory_unlock']) if (!migration.includes(marker)) throw new Error(`migration ordering is missing ${marker}`);
const health = read('src/app/api/healthz/route.ts');
for (const marker of ["status: 'ready'", "status: 'not_ready'", 'cache-control']) if (!health.includes(marker)) throw new Error(`health route is missing ${marker}`);
console.log(JSON.stringify({status: 'PASS', profile: 'local-preflight', checks, productionDeployment: 'NOT_RUN', externalAccounts: 'NOT_PROVIDED'}, null, 2));
